#!/usr/bin/env python3
"""Generate every platform's token file from tokens.json, the single source of truth.

    python3 tools/build_tokens.py           write the files under kit/
    python3 tools/build_tokens.py --check   exit 1 if any generated file is out of date

Never edit the generated files by hand: change tokens.json and run this again.
Uses only the Python standard library.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
T = json.loads((ROOT / "tokens.json").read_text())
THEMES = list(T["themes"])
NOTE = "Generated by tools/build_tokens.py from tokens.json. Do not edit."


def base_colors():
    """Shared colours: the dark world plus the UI layer. name -> lower-case hex."""
    out = {k: v["value"].lower() for k, v in T["color"].items()}
    out.update({k: v["value"].lower() for k, v in T["ui"]["color"].items()})
    return out


def theme_colors(name):
    """Colours for one theme: the shared set with that theme's lights laid over it."""
    out = base_colors()
    out.update({k: v.lower() for k, v in T["themes"][name]["color"].items()})
    return out


def light_keys():
    """Every token that at least one theme overrides, in a stable order."""
    keys = []
    for n in THEMES:
        for k in T["themes"][n]["color"]:
            if k not in keys:
                keys.append(k)
    return keys


def halo(hex_color, alpha=0.5):
    r, g, b = (int(hex_color[i:i + 2], 16) for i in (1, 3, 5))
    return f"rgba({r},{g},{b},{alpha})"


FONTS = {
    "display": '"Pixelify Sans", "Silkscreen", monospace',
    "label": '"Silkscreen", "Pixelify Sans", monospace',
    "body": '"IBM Plex Sans", "Noto Sans", system-ui, sans-serif',
    "code": '"VT323", "Courier New", monospace',
}


def web_css():
    lines = [f"/* {NOTE} */", "/* Ember is the default. Set data-glow=\"forge\" or \"frost\" on any element to switch. */", ":root {", "  color-scheme: dark;"]
    for k, v in theme_colors("ember").items():
        lines.append(f"  --{k}: {v};")
    lines.append(f"  --accent-halo: {halo(theme_colors('ember')['accent'])};")
    for k, v in FONTS.items():
        lines.append(f"  --{k}: {v};")
    s = T["ui"]["size"]
    for k in ("border", "border-focus", "edge", "ring", "shadow-sm", "shadow-md", "shadow-lg", "bar-height", "panel-pad", "gap"):
        lines.append(f"  --{k}: {s[k]['value']}px;")
    m = T["ui"]["motion"]
    lines.append(f"  --press: {m['press']['ms']}ms steps({m['press']['steps']});")
    lines.append(f"  --toggle: {m['toggle']['ms']}ms steps({m['toggle']['steps']});")
    lines.append(f"  --move: {m['move']['ms']}ms;")
    lines.append("}")
    for name in THEMES:
        if name == "ember":
            continue
        lines.append(f'[data-glow="{name}"] {{')
        for k, v in T["themes"][name]["color"].items():
            lines.append(f"  --{k}: {v.lower()};")
        lines.append(f"  --accent-halo: {halo(theme_colors(name)['accent'])};")
        lines.append("}")
    return "\n".join(lines) + "\n"


def gtk_css(name):
    lines = [f"/* {NOTE} */", f"/* Glowgrid {name.title()} for GTK 4: load this file before kit/gtk4/glowgrid.css. */"]
    for k, v in theme_colors(name).items():
        lines.append(f"@define-color gg_{k.replace('-', '_')} {v};")
    return "\n".join(lines) + "\n"


def qml():
    def obj(d):
        return "{ " + ", ".join(f'"{k.replace("-", "_")}": "{v}"' for k, v in d.items()) + " }"
    lines = [f"// {NOTE}", "// Glowgrid tokens for Qt Quick / Quickshell. Set `name` to \"ember\", \"forge\" or \"frost\".", "pragma Singleton", "import QtQuick", "", "QtObject {", '    property string name: "ember"', "    readonly property var themes: ({"]
    for n in THEMES:
        lines.append(f"        {n}: {obj({k: theme_colors(n)[k] for k in light_keys()})},")
    lines += ["    })", "    readonly property var t: themes[name] || themes.ember", "", "    // the dark world and the UI layer, shared by every theme"]
    lights = light_keys()
    for k, v in base_colors().items():
        if k not in lights:
            lines.append(f'    readonly property color {camel(k)}: "{v}"')
    lines.append("")
    lines.append("    // the lights, from the active theme")
    for k in lights:
        lines.append(f"    readonly property color {camel(k)}: t.{k.replace('-', '_')}")
    lines.append("")
    for k, v in (("display", "Pixelify Sans"), ("label", "Silkscreen"), ("code", "VT323"), ("body", "IBM Plex Sans")):
        lines.append(f'    readonly property string {k}: "{v}"')
    s = T["ui"]["size"]
    lines.append("")
    for k in ("border", "border-focus", "edge", "ring", "shadow-sm", "shadow-md", "shadow-lg", "bar-height", "panel-pad", "gap"):
        lines.append(f"    readonly property int {camel(k)}: {s[k]['value']}")
    m = T["ui"]["motion"]
    lines.append(f"    readonly property int pressMs: {m['press']['ms']}")
    lines.append(f"    readonly property int toggleMs: {m['toggle']['ms']}")
    lines.append(f"    readonly property int moveMs: {m['move']['ms']}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def camel(k):
    parts = k.split("-")
    return parts[0] + "".join(p.title() for p in parts[1:])


def rust():
    lines = [f"// {NOTE}", "//! Glowgrid tokens. `palette(name)` returns the lights of a theme; the rest is shared.", "", "#![allow(dead_code)]", ""]
    lights = light_keys()
    for k, v in base_colors().items():
        if k not in lights:
            lines.append(f'pub const {k.upper().replace("-", "_")}: &str = "{v}";')
    lines += ["", "pub struct Palette {"]
    for k in lights:
        lines.append(f"    pub {k.replace('-', '_')}: &'static str,")
    lines += ["}", "", f"pub const THEMES: [&str; {len(THEMES)}] = [{', '.join(chr(34) + n + chr(34) for n in THEMES)}];", "", "pub fn palette(name: &str) -> Palette {", "    match name {"]
    for n in THEMES:
        if n != "ember":
            fields = ", ".join(f'{k.replace("-", "_")}: "{theme_colors(n)[k]}"' for k in lights)
            lines.append(f'        "{n}" => Palette {{ {fields} }},')
    fields = ", ".join(f'{k.replace("-", "_")}: "{theme_colors("ember")[k]}"' for k in lights)
    lines.append(f"        _ => Palette {{ {fields} }},")
    lines += ["    }", "}"]
    return "\n".join(lines) + "\n"


ANSI = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"]


def kitty(name):
    t = T["themes"][name]["terminal"]
    lines = [f"# {NOTE}", f"# Glowgrid {name.title()} for kitty: `include` this file from kitty.conf.",
             f"foreground            {t['foreground'].lower()}", f"background            {t['background'].lower()}",
             f"selection_foreground  {t['selection-fg'].lower()}", f"selection_background  {t['selection-bg'].lower()}",
             f"cursor                {t['cursor'].lower()}", f"cursor_text_color     {t['background'].lower()}",
             f"url_color             {theme_colors(name)['glow-3']}",
             f"active_tab_foreground   {theme_colors(name)['ink']}", f"active_tab_background   {theme_colors(name)['accent']}",
             f"inactive_tab_foreground {theme_colors(name)['text-soft']}", f"inactive_tab_background {theme_colors(name)['surface']}",
             f"tab_bar_background      {theme_colors(name)['bg']}"]
    for i, c in enumerate(ANSI):
        lines.append(f"color{i:<2} {t['normal'][c].lower()}")
        lines.append(f"color{i + 8:<2} {t['bright'][c].lower()}")
    return "\n".join(lines) + "\n"


def console(name):
    """16 hex colours without '#', the form the Linux console and NixOS `console.colors` take.
    Colour 0 is the background (bg), not ANSI black, because the console paints the screen with it."""
    t = T["themes"][name]["terminal"]
    cols = [t["background"]] + [t["normal"][c] for c in ANSI[1:]] + [t["bright"][c] for c in ANSI]
    return f"# {NOTE}\n" + "\n".join(c.lower().lstrip("#") for c in cols) + "\n"


def terminal_json(name):
    t = T["themes"][name]["terminal"]
    return json.dumps({"name": f"Glowgrid {name.title()}", **{k: (v if isinstance(v, dict) else v) for k, v in t.items()}}, indent=2).lower().replace('"name": "glowgrid', '"name": "Glowgrid') + "\n"


def noctalia(name):
    c, t = theme_colors(name), T["themes"][name]["terminal"]
    d = {"mPrimary": c["accent"], "mOnPrimary": c["ink"], "mSecondary": c["glow-3"], "mOnSecondary": c["bg"], "mTertiary": c["glow-2"], "mOnTertiary": c["bg"],
         "mError": c["alert"], "mOnError": c["bg"], "mSurface": c["surface"], "mOnSurface": c["text"], "mSurfaceVariant": "#241433", "mOnSurfaceVariant": c["text-soft"],
         "mOutline": c["stone"], "mShadow": "#000000", "mHover": c["stone"], "mOnHover": c["accent-hot"],
         "terminal": {"foreground": t["foreground"].lower(), "background": t["background"].lower(), "selectionFg": t["selection-fg"].lower(), "selectionBg": t["selection-bg"].lower(),
                      "cursorText": t["background"].lower(), "cursor": t["cursor"].lower(),
                      "normal": {k: v.lower() for k, v in t["normal"].items()}, "bright": {k: v.lower() for k, v in t["bright"].items()}}}
    return json.dumps({"dark": d, "light": d}, indent=2) + "\n"


def outputs():
    icons = json.loads((ROOT / "kit/icons/icons.json").read_text())["icons"]
    icons_js = (f"// {NOTE} (source: kit/icons/icons.json)\n"
                "// ggIcon(name, cell = 2) returns an inline <svg> string in the current text colour.\n"
                f"const GLOWGRID_ICONS = {json.dumps(icons, separators=(',', ':'))};\n"
                "function ggIcon(name, cell = 2) {\n"
                "  const rows = GLOWGRID_ICONS[name] || GLOWGRID_ICONS.question, n = 7 * cell;\n"
                "  let r = '';\n"
                "  rows.forEach((row, j) => [...row].forEach((b, i) => { if (b === '1') r += `<rect x=\"${i * cell}\" y=\"${j * cell}\" width=\"${cell}\" height=\"${cell}\"/>`; }));\n"
                "  return `<svg class=\"gg-icon\" width=\"${n}\" height=\"${n}\" viewBox=\"0 0 ${n} ${n}\" aria-hidden=\"true\">${r}</svg>`;\n"
                "}\n"
                "// <i data-gg-icon=\"copy\"></i> elements are filled in on load\n"
                "if (typeof document !== 'undefined') document.addEventListener('DOMContentLoaded', () =>\n"
                "  document.querySelectorAll('[data-gg-icon]').forEach(e => { e.outerHTML = ggIcon(e.dataset.ggIcon, +(e.dataset.cell || 2)); }));\n")
    out = {"kit/web/tokens.css": web_css(), "kit/web/icons.js": icons_js, "kit/qml/Glowgrid.qml": qml(), "kit/rust/tokens.rs": rust()}
    for n in THEMES:
        out[f"kit/gtk4/tokens-{n}.css"] = gtk_css(n)
        out[f"kit/terminal/kitty-{n}.conf"] = kitty(n)
        out[f"kit/terminal/console-{n}.txt"] = console(n)
        out[f"kit/terminal/{n}.json"] = terminal_json(n)
        out[f"kit/noctalia/glowgrid-{n}.json"] = noctalia(n)
    return out


def main():
    check = "--check" in sys.argv
    stale = []
    for rel, text in outputs().items():
        path = ROOT / rel
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if check:
        if stale:
            print("Out of date (run tools/build_tokens.py):\n  " + "\n  ".join(stale))
            return 1
        print(f"{len(outputs())} generated files are up to date")
        return 0
    print(f"wrote {len(outputs())} files under kit/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
